SEC_LABEL = {'A': 'MCQs', 'B': 'Short Questions', 'C': 'Detailed Answers'}


def sec(unit, letter):
    return f'Exercise {unit} {SEC_LABEL[letter]}'


def q(qid, unit, letter, number, qtype, question, answer, explanation, pdf_page,
      options=None, correct=None, figure=None):
    d = {
        'id': qid,
        'chapter': unit,
        'section': sec(unit, letter),
        'sectionCode': f'EX{unit}{letter}',
        'type': qtype,
        'number': number,
        'question': question,
        'answer': answer,
        'explanation': explanation,
        'pdfPage': pdf_page,
        'bookPage': pdf_page - 5,
        'figure': figure,
    }
    if qtype == 'mcq':
        d['options'] = [{'key': k, 'text': t} for k, t in options]
        d['optionsRaw'] = '  '.join(f'({k}) {t}' for k, t in options)
        d['correctAnswer'] = correct
    return d


