def q(lesson, section, sectionCode, number, question, answer,
      explanation=None, pdfPage=None, bookPage=None, figure=False):
    """Create one solved-question dict."""
    d = {
        "id": f"L{lesson}_{sectionCode}{number}",
        "lesson": lesson,
        "section": section,
        "sectionCode": sectionCode,
        "type": "solved",
        "number": number,
        "question": question,
        "answer": answer,
    }
    if explanation:
        d["explanation"] = explanation
    if pdfPage is not None:
        d["pdfPage"] = pdfPage
    if bookPage is not None:
        d["bookPage"] = bookPage
    if figure:
        d["figure"] = True
    return d


